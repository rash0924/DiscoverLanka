export const getDestinationBySlug = (slug: string): Destination | undefined =>
  DESTINATIONS.find((d) => d.slug === slug);

export const getDestinationsByDistrict = (districtId: string): Destination[] =>
  DESTINATIONS.filter((d) => d.districtId === districtId);

export const getFeaturedDestinations = (): Destination[] =>
  DESTINATIONS.filter((d) => d.isFeatured);

export const getTrendingDestinations = (): Destination[] =>
  DESTINATIONS.filter((d) => d.isTrending);

export const searchDestinations = (query: string): Destination[] => {
  const q = query.toLowerCase();
  return DESTINATIONS.filter(
    (d) =>
      d.name.toLowerCase().includes(q) ||
      d.district.toLowerCase().includes(q) ||
      d.province.toLowerCase().includes(q) ||
      d.categories.some((c) => c.toLowerCase().includes(q)) ||
      d.shortDescription.toLowerCase().includes(q)
  );
};
